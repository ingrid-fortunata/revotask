"""Alembic environment for RevoTask (DB06, FND-AC5.3, FND-AC5.7, FND-AC5.8).

Generated by `flask db init`, then edited. The edits are:
- Migrations use a dedicated engine with search_path=public. The PostgreSQL role is named
  revotask, so its "$user" search path entry resolves to a schema named revotask too. With the
  default path, Alembic reflects the same tables twice and reports false differences. Every
  RevoTask object is referenced by its schema-qualified name, so the empty public schema adds
  nothing.
- The revotask schema must already exist. Migrations never create it, and they check first.
- Connection failures print a fixed message and never print the database URL.
"""

import logging
from logging.config import fileConfig

import click
from alembic import context
from flask import current_app
from sqlalchemy import create_engine, text
from sqlalchemy.exc import OperationalError
from sqlalchemy.pool import NullPool

from app.config import DB_SCHEMA

# this is the Alembic Config object, which provides access to the values within the .ini file.
config = context.config

# Interpret the config file for Python logging.
if config.config_file_name is not None:
    # disable_existing_loggers=False keeps the revotask.* loggers enabled after Alembic loads.
    fileConfig(config.config_file_name, disable_existing_loggers=False)
logger = logging.getLogger("alembic.env")


def get_metadata():
    return current_app.extensions["migrate"].db.metadata


def get_migration_engine():
    """Engine for migrations, pinned to search_path=public. The app engine is unchanged."""
    url = current_app.config["SQLALCHEMY_DATABASE_URI"]
    return create_engine(
        url,
        poolclass=NullPool,
        connect_args={"options": "-c search_path=public"},
    )


def require_schema(connection):
    """Stop before any DDL when the schema is missing. The message names the next command."""
    exists = connection.execute(
        text("SELECT 1 FROM pg_namespace WHERE nspname = :name"), {"name": DB_SCHEMA}
    ).first()
    if exists is None:
        raise click.ClickException(
            f"Schema '{DB_SCHEMA}' does not exist. Run: flask --app app:create_app bootstrap-schema"
        )


def run_migrations_offline():
    """Offline mode renders SQL without a connection, so the schema check is skipped."""
    url = current_app.config["SQLALCHEMY_DATABASE_URI"]
    context.configure(
        url=url,
        target_metadata=get_metadata(),
        literal_binds=True,
        version_table_schema=DB_SCHEMA,
        include_schemas=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online():
    """Run against the live database. Verify the schema before the first DDL statement."""

    # Prevent an empty autogenerate revision when no schema change is detected.
    def process_revision_directives(context, revision, directives):
        if getattr(config.cmd_opts, "autogenerate", False):
            script = directives[0]
            if script.upgrade_ops.is_empty():
                directives[:] = []
                logger.info("No changes in schema detected.")

    conf_args = dict(current_app.extensions["migrate"].configure_args)
    conf_args.setdefault("process_revision_directives", process_revision_directives)

    try:
        engine = get_migration_engine()
        # Check on a separate connection. A SELECT on the migration connection would autobegin
        # a transaction, and Alembic would then skip its own commit and roll back all DDL.
        with engine.connect() as check_connection:
            require_schema(check_connection)
        with engine.connect() as connection:
            context.configure(
                connection=connection,
                target_metadata=get_metadata(),
                **conf_args,
            )
            with context.begin_transaction():
                context.run_migrations()
    except OperationalError:
        raise click.ClickException("Cannot reach the database.") from None
    finally:
        engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
